-- =====================================================================
--  Миграция 5: объединяет учётные записи IT-специалистов с их записями
--  в общем списке сотрудников клиники.
--
--  Изначально (db/schema.sql) Александр Вавилов и Никита Павлов заводились
--  как ОТДЕЛЬНЫЕ записи (role='it', без записи в списке сотрудников).
--  Выяснилось, что оба они и так есть в общем списке сотрудников клиники
--  (db/seed_employees.sql) под теми же ФИО с отчествами — то есть на
--  каждого получилось по ДВЕ записи с одинаковым ФИО, что невозможно
--  из-за уникальности поля full_name, и вызывало ошибку при входе.
--
--  Этот скрипт: удаляет временную запись 'it' (по telegram_id) и переносит
--  роль/telegram_id/цвет на настоящую запись сотрудника (по ФИО с
--  отчеством) — пароль и его текущее состояние (менял/не менял) при этом
--  не трогаются. Выполните один раз через phpMyAdmin (вкладка «SQL»).
-- =====================================================================

-- Александр Вавилов
DELETE FROM users
WHERE telegram_id = 1126928689
  AND full_name <> 'Вавилов Александр Игоревич';

UPDATE users SET role = 'it', telegram_id = 1126928689, badge_color = 'purple'
WHERE full_name = 'Вавилов Александр Игоревич';

-- Никита Павлов
DELETE FROM users
WHERE telegram_id = 98303100
  AND full_name <> 'Павлов Никита Максимович';

UPDATE users SET role = 'it', telegram_id = 98303100, badge_color = 'blue'
WHERE full_name = 'Павлов Никита Максимович';
